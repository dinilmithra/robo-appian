"""Deterministic pytest generation using public RoboAppian calls only."""
from __future__ import annotations

import ast
from pathlib import Path
from .model import Recording


def expression(target: dict) -> str:
    kind = target["component"]
    if kind == "menu":
        return "page" + "".join(f".menu(name={name!r})" for name in target["path"])
    if kind == "grid_cell":
        grid = target["grid"]
        return (f"page.grid(header={grid['header']!r}).cell("
                f"row_number={grid['row_number']}, column_name={grid['column_name']!r})")
    base = "page"
    if target.get("dialog"):
        base += f".dialog(name={target['dialog']!r})"
    if kind == "text":
        return f"{base}.text({target['name']!r})"
    key = "name" if kind in {"button", "link", "tab"} else ("label" if target.get("label") else "placeholder")
    return f"{base}.{kind}({key}={target[key]!r})"


def generate_pytest(recording: Recording) -> str:
    errors = recording.export_issues()
    if errors:
        raise ValueError("Export blocked:\n" + "\n".join(errors))
    data = {}; lines = []
    for index, step in enumerate(recording.data["steps"], 1):
        target, action = step["target"], step["action"]
        component = expression(target)
        key = f"value_{index:03d}"; ref = f"recorded_data[{key!r}]"
        if action in {"fill", "select", "assert_value", "assert_text"} and target["component"] != "tab":
            data[key] = step["value"]
        if action == "fill":
            line = f"{component}.fill({ref})"
        elif action == "select":
            if target["component"] == "tab":
                line = f"{component}.select()"
            elif target["component"] == "textbox":
                search_key = f"search_{index:03d}"; data[search_key] = step["search_text"]
                line = f"{component}.select(search_text=recorded_data[{search_key!r}], value={ref})"
            else:
                line = f"{component}.select(value={ref})"
        elif action in {"check", "uncheck", "open"}:
            line = f"{component}.{action}()"
        elif action == "click":
            line = f"{component}.click(" + ("opens_new_page=False" if target["component"] == "menu" else "") + ")"
        elif action == "assert_visible":
            if target["component"] == "button":
                line = (f"page.wait_until(lambda: {component}.is_visible(), timeout=wait_time, "
                        f"message={'Recorded button did not become visible.'!r})")
            else:
                line = f"{component}.wait_until_visible()"
        elif action == "assert_value":
            # Date normalized by the public component before comparing display.
            expected = f"AppianDate.normalize({ref})" if target["component"] == "date" else ref
            line = (f"page.wait_until(lambda: {component}.value == {expected}, timeout=wait_time, "
                    f"message={'Recorded field value did not match its approved expectation.'!r})")
        elif action == "assert_text":
            line = (f"page.wait_until(lambda: {component}.text() == {ref}, timeout=wait_time, "
                    f"message={'Recorded grid cell did not match its approved expectation.'!r})")
        else:
            raise ValueError(f"Unsupported action: {action}")
        lines.append(f"    # {step['id']}: approved {action}\n    {line}")
    source = (
        '# Generated by robo_appian.recorder. Review business expectations before use.\n'
        '# The consumer page fixture must authenticate and clean up each fresh session.\n'
        'import pytest\nfrom robo_appian import AppianDate, AppianPage\n\n'
        f'RECORDED_DATA = {data!r}\n\n'
        '@pytest.mark.parametrize("recorded_data", [RECORDED_DATA])\n'
        'def test_recorded_workflow(page: AppianPage, wait_time: int, recorded_data):\n'
        f'    page.goto({recording.data["start_url"]!r})\n'
        + '\n'.join(lines) + '\n'
    )
    ast.parse(source)
    return source


def write_pytest(recording: Recording, path: str | Path) -> Path:
    path = Path(path)
    source = generate_pytest(recording)
    if path.exists():
        raise FileExistsError(f"Refusing to overwrite {path}; choose a new output name.")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")
    return path
